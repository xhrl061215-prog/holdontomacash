/**
 * Generates supabase/SETUP.sql — every migration concatenated, in order, into one
 * file that can be pasted into the Supabase SQL editor a single time.
 *
 * Generated rather than hand-maintained: a hand-copied bundle silently drifts from
 * the real migrations, and the drift only shows up as a broken deployment. This
 * reads MIGRATIONS from server/index.mjs, so the bundle cannot contain a
 * different set of files than the app itself applies.
 *
 * Run: npm run build:setup-sql
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migDir = join(root, 'supabase', 'migrations')

// Single source of truth: the list the running app applies.
const serverSrc = readFileSync(join(root, 'server', 'index.mjs'), 'utf8')
const block = serverSrc.match(/const MIGRATIONS = \[([\s\S]*?)\]/)
if (!block) throw new Error('Could not find MIGRATIONS in server/index.mjs')
const files = [...block[1].matchAll(/'([^']+\.sql)'/g)].map((m) => m[1])
if (files.length === 0) throw new Error('MIGRATIONS list is empty')

const parts = [
  `-- =====================================================================`,
  `-- BudgetTracker — complete database setup`,
  `--`,
  `-- Paste this ENTIRE file into the Supabase SQL Editor and press Run, once.`,
  `-- It creates every table, security policy, default category and function the`,
  `-- app needs. Safe to run more than once: re-running changes nothing.`,
  `--`,
  `-- Generated from supabase/migrations/ by scripts/build-setup-sql.mjs.`,
  `-- Do not edit this file directly — edit the migrations and regenerate.`,
  `--`,
  `-- Contains ${files.length} migrations, in order:`,
  ...files.map((f, i) => `--   ${i + 1}. ${f}`),
  `-- =====================================================================`,
  ``,
  `begin;`,
  ``,
]

for (const [i, f] of files.entries()) {
  const sql = readFileSync(join(migDir, f), 'utf8').trimEnd()
  parts.push(
    `-- ---------------------------------------------------------------------`,
    `-- ${i + 1}/${files.length}: ${f}`,
    `-- ---------------------------------------------------------------------`,
    ``,
    sql,
    ``,
    ``,
  )
}

// One transaction: a failure part-way through rolls the whole thing back rather
// than leaving a half-built database that is harder to diagnose than an empty one.
parts.push(`commit;`, ``)
parts.push(
  `-- Done. Expected result: "Success. No rows returned".`,
  `-- Verify with:  select count(*) from public.categories;   -- 0 until someone signs up`,
  ``,
)

const out = parts.join('\n')
writeFileSync(join(root, 'supabase', 'SETUP.sql'), out)

console.log(`Wrote supabase/SETUP.sql`)
console.log(`  ${files.length} migrations, ${out.split('\n').length} lines`)
files.forEach((f, i) => console.log(`  ${i + 1}. ${f}`))
